function setNestedValue(target, path, value) {
    const lastKey = path[path.length - 1];

    const parent = path.slice(0, -1).reduce((current, key) => {
        current[key] ??= {};
        return current[key];
    }, target);

    parent[lastKey] = value;
}

function formatTypeScript({ dictionary }) {
    const tokens = {};

    for (const token of dictionary.allTokens) {
        // Prefer the resolved value, falling back to DTCG source values.
        const value =
            token.value ??
            token.$value ??
            token.original?.$value ??
            token.original?.value;

        if (value === undefined) {
            throw new Error(`Missing value for token: ${token.path.join('.')}`);
        }

        setNestedValue(tokens, token.path, value);
    }

    return [
        '// Generated by Style Dictionary. Do not edit.',
        '',
        `export const tokens = ${JSON.stringify(tokens, null, 2)} as const;`,
        '',
        'export default tokens;',
        '',
    ].join('\n');
}

export default {
    source: ['src/**/*.json'],

    hooks: {
        formats: {
            'typescript/tokens': formatTypeScript,
        },
    },

    platforms: {
        css: {
            transformGroup: 'css',
            buildPath: 'dist/',
            files: [
                {
                    destination: 'tokens.css',
                    format: 'css/variables',
                    options: {
                        outputReferences: true,
                    },
                },
            ],
        },

        typescript: {
            transforms: [],
            buildPath: 'dist/',
            files: [
                {
                    destination: 'tokens.ts',
                    format: 'typescript/tokens',
                },
            ],
        },
    },
};
